//! Emitting the spec-example round-trip corpus (`tests/spec_examples*`).
//!
//! Every request example (`x-example`) and JSON success response example
//! must deserialize into its generated type and serialize back without
//! losing fields. `tests/spec_examples/roundtrip.rs` (hand-written) does the
//! comparison; this module writes the data and the per-group test table.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::json;

use super::ir::{Example, Ir, Output, Ty};

/// The Rust type of `ty` as seen from an integration test.
fn ty_path(ty: &Ty) -> String {
    match ty {
        Ty::String => "String".into(),
        Ty::I32 => "i32".into(),
        Ty::I64 => "i64".into(),
        Ty::F64 => "f64".into(),
        Ty::Bool => "bool".into(),
        Ty::Value => "serde_json::Value".into(),
        Ty::Vec(t) => format!("Vec<{}>", ty_path(t)),
        Ty::Map(t) => format!("std::collections::BTreeMap<String, {}>", ty_path(t)),
        Ty::Model(n) => format!("models::{n}"),
    }
}

struct Case<'a> {
    id: String,
    ty: String,
    example: &'a Example,
}

/// Returns (`tests/spec_examples.rs`, `tests/spec_examples/examples.json`).
pub fn generate(ir: &Ir, allowlist: &BTreeMap<String, String>) -> (String, String) {
    let mut by_group: BTreeMap<&str, Vec<Case>> = BTreeMap::new();
    for op in &ir.operations {
        let cases = by_group.entry(&op.group).or_default();
        if let Some(body) = &op.body {
            for example in &op.request_examples {
                cases.push(Case {
                    id: format!("{}:request:{}", op.id, example.name),
                    ty: ty_path(body),
                    example,
                });
            }
        }
        for (status, example) in &op.response_examples {
            let ty = match &op.output {
                Output::Json(ty) => Some(ty),
                Output::ByStatus(variants) => variants
                    .iter()
                    .find(|(s, _)| s == status)
                    .and_then(|(_, t)| t.as_ref()),
                _ => None,
            };
            if let Some(ty) = ty {
                cases.push(Case {
                    id: format!("{}:response:{status}", op.id),
                    ty: ty_path(ty),
                    example,
                });
            }
        }
    }
    by_group.retain(|_, cases| !cases.is_empty());

    let mut rs = String::from(
        "// @generated by `cargo xtask codegen` from spec/cybersource-rest-spec.json.\n\
         // Do not edit by hand; change the generator or spec/codegen.toml instead.\n\n\
         //! Every spec example must round-trip through its generated type.\n\n\
         #![cfg(feature = \"server\")]\n\
         #![allow(unused_imports)]\n\n\
         #[path = \"spec_examples/roundtrip.rs\"]\n\
         mod roundtrip;\n\n\
         use cybersource::models;\n\
         use roundtrip::check;\n",
    );
    let mut data = serde_json::Map::new();
    for (group, cases) in &by_group {
        let test = group.replace('-', "_");
        write!(
            rs,
            "\n#[cfg(feature = \"{group}\")]\n#[test]\nfn {test}() {{\n    roundtrip::run(&[\n"
        )
        .unwrap();
        for case in cases {
            writeln!(rs, "        ({:?}, check::<{}>),", case.id, case.ty).unwrap();
            data.insert(
                case.id.clone(),
                json!({
                    "value": case.example.value,
                    "ignore": case.example.ignore,
                    "skip": case.example.skip,
                }),
            );
        }
        rs.push_str("    ]);\n}\n");
    }
    let json = serde_json::to_string_pretty(&json!({
        "allowlist": allowlist,
        "examples": data,
    }))
    .expect("examples serialize");
    (rs, json + "\n")
}
