fn model_field(field: &Field) -> TokenStream {
    let doc = doc_attrs(field.doc.as_deref());
    let name = ident(&field.rust_name);
    let ty = rust_ty(&field.ty);
    let json = &field.json_name;
    let rename = (field.rust_name.trim_start_matches("r#") != json.as_str())
        .then(|| quote! { rename = #json, });
    let lenient = lenient_fn(&field.ty).map(|f| quote! { deserialize_with = #f, });
    quote! {
        #doc
        #[serde(#rename skip_serializing_if = "Option::is_none", #lenient)]
        pub #name: Option<#ty>,
    }
}

fn redacting_debug(model: &Model) -> TokenStream {
    let name = ident(&model.name);
    let label = &model.name;
    let fields = model.fields.iter().map(|f| {
        let field = ident(&f.rust_name);
        let label = f.rust_name.trim_start_matches("r#");
        if f.sensitive {
            quote! { .field(#label, &self.#field.as_ref().map(|_| "[REDACTED]")) }
        } else {
            quote! { .field(#label, &self.#field) }
        }
    });
    quote! {
        impl ::std::fmt::Debug for #name {
            fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
                f.debug_struct(#label) #(#fields)* .finish()
            }
        }
    }
}

pub fn model(model: &Model, cfg: Option<TokenStream>) -> TokenStream {
    let name = ident(&model.name);
    let doc = doc_attrs(model.doc.as_deref());
    let alias = model
        .alias
        .as_deref()
        .map(|a| quote! { #[doc(alias = #a)] });
    let fields = model.fields.iter().map(model_field);
    let sensitive = model.fields.iter().any(|f| f.sensitive);
    let debug_derive = (!sensitive).then(|| quote! { Debug, });
    let debug_impl = sensitive.then(|| {
        let imp = redacting_debug(model);
        quote! { #cfg #imp }
    });
    quote! {
        #doc
        #alias
        #cfg
        #[derive(#debug_derive Clone, Default, PartialEq, ::serde::Serialize, ::serde::Deserialize)]
        #[serde(default)]
        pub struct #name {
            #(#fields)*
        }
        #debug_impl
    }
}

fn models(ir: &Ir, files: &mut Files) {
    let mut by_file: BTreeMap<String, Vec<TokenStream>> = BTreeMap::new();
    for m in ir.models.values() {
        if m.groups.len() == 1 {
            let group = m.groups.iter().next().unwrap();
            by_file
                .entry(group.clone())
                .or_default()
                .push(model(m, None));
        } else {
            by_file
                .entry("shared".into())
                .or_default()
                .push(model(m, Some(cfg_any(&m.groups))));
        }
    }
    let mut mod_items = Vec::new();
    for (file, items) in &by_file {
        let module = format_ident!("{}", file.replace('-', "_"));
        let cfg = (file != "shared").then(|| cfg_any([file]));
        mod_items.push(quote! {
            #cfg mod #module;
            #cfg #[allow(unused_imports)] pub use #module::*;
        });
        files.insert(
            format!("models/{}.rs", file.replace('-', "_")),
            render(quote! {
                #[allow(unused_imports)]
                use super::*;
                #(#items)*
            }),
        );
    }
    files.insert(
        "models/mod.rs".into(),
        render(quote! {
            //! Request and response models generated from the spec.
            #(#mod_items)*
        }),
    );
}

