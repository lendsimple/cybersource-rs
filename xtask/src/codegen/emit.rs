pub fn group_type_name(group: &str) -> String {
    group.to_upper_camel_case()
}

pub fn api_group(group: &str, ops: &[&Operation]) -> TokenStream {
    let ty = format_ident!("{}", group_type_name(group));
    let accessor = format_ident!("{}", group.replace('-', "_"));
    let ops_mod = format_ident!("{}", group.replace('-', "_"));
    let type_doc = doc_line(&format!(
        "The `{group}` operations; from `client.{accessor}()`."
    ));
    let accessor_doc = doc_line(&format!("The `{group}` operations."));

    let methods = ops.iter().map(|op| {
        let fn_name = ident(&op.fn_name);
        let op_ty = ident(&op.struct_name);
        let doc = doc_line(&op_doc(op));
        let required: Vec<&Param> = op.params.iter().filter(|p| p.required).collect();
        let args = required.iter().map(|p| {
            let n = ident(&p.rust_name);
            let (ty, _) = param_arg(p);
            quote! { #n: #ty }
        });
        let body_arg = op.body.as_ref().map(|t| {
            let t = qualified_ty(t);
            quote! { body: #t }
        });
        let all_args: Vec<TokenStream> = args.chain(body_arg).collect();
        let pass = required
            .iter()
            .map(|p| {
                let n = ident(&p.rust_name);
                quote! { #n }
            })
            .chain(op.body.as_ref().map(|_| quote! { body }));
        quote! {
            #doc
            #[allow(clippy::too_many_arguments)]
            pub fn #fn_name(&self, #(#all_args),*) -> Call<'c, C, ops::#op_ty> {
                Call::new(self.client, ops::#op_ty::new(#(#pass),*))
            }
        }
    });

    let call_setters = ops
        .iter()
        .filter(|op| op.params.iter().any(|p| !p.required))
        .map(|op| {
            let op_ty = ident(&op.struct_name);
            let setters = op.params.iter().filter(|p| !p.required).map(|p| {
                let n = ident(&p.rust_name);
                let (ty, conv) = param_arg(p);
                let doc = doc_line(&format!("Sets `{}`.", p.json_name));
                quote! {
                    #doc
                    pub fn #n(self, #n: #ty) -> Self { self.map_op(|op| op.#n = Some(#conv)) }
                }
            });
            quote! {
                impl<C> Call<'_, C, ops::#op_ty> {
                    #(#setters)*
                }
            }
        });

    quote! {
        use crate::call::Call;
        use crate::client::Client;
        #[cfg(not(target_family = "wasm"))]
        use crate::client::BlockingClient;
        use crate::operations::#ops_mod as ops;

        #type_doc
        #[derive(Debug, Clone, Copy)]
        pub struct #ty<'c, C> {
            client: &'c C,
        }

        impl<T> Client<T> {
            #accessor_doc
            pub fn #accessor(&self) -> #ty<'_, Self> {
                #ty { client: self }
            }
        }

        #[cfg(not(target_family = "wasm"))]
        impl<T> BlockingClient<T> {
            #accessor_doc
            pub fn #accessor(&self) -> #ty<'_, Self> {
                #ty { client: self }
            }
        }

        impl<'c, C> #ty<'c, C> {
            #(#methods)*
        }

        #(#call_setters)*
    }
}

fn apis(ir: &Ir, files: &mut Files) {
    let mut by_group: BTreeMap<&str, Vec<&Operation>> = BTreeMap::new();
    for op in &ir.operations {
        by_group.entry(&op.group).or_default().push(op);
    }
    let mut mod_items = Vec::new();
    for (group, ops) in &by_group {
        let module = format_ident!("{}", group.replace('-', "_"));
        let ty = format_ident!("{}", group_type_name(group));
        let cfg = cfg_any([group]);
        mod_items.push(quote! {
            #cfg mod #module;
            #cfg pub use #module::#ty;
        });
        files.insert(
            format!("apis/{}.rs", group.replace('-', "_")),
            render(api_group(group, ops)),
        );
    }
    files.insert(
        "apis/mod.rs".into(),
        render(quote! {
            //! Per-group accessors (`client.payments()`, `client.tms()`, ...).
            #(#mod_items)*
        }),
    );
}

/// Checks emitter-level naming rules the IR cannot know about.
pub fn validate(ir: &Ir) -> Vec<String> {
    let mut errors = Vec::new();
    for name in ir.models.keys() {
        if RESERVED_MODEL_NAMES.contains(&name.as_str()) {
            errors.push(format!(
                "model `{name}` would shadow a name the generated code uses; rename it under [model_renames]"
            ));
        }
    }
    for op in &ir.operations {
        let mut path = op.path.clone();
        for p in op.params.iter().filter(|p| p.location == ParamIn::Path) {
            path = path.replace(&format!("{{{}}}", p.json_name), "");
        }
        if path.contains('{') {
            errors.push(format!(
                "{} {}: path placeholder without a matching path parameter",
                op.method, op.path
            ));
        }
        for p in op.params.iter().filter(|p| !p.required) {
            if CALL_METHODS.contains(&p.rust_name.as_str()) || p.rust_name == "body" {
                errors.push(format!(
                    "{} {}: optional parameter `{}` clashes with a Call method",
                    op.method, op.path, p.rust_name
                ));
            }
        }
    }
    errors
}

/// Generates every file.
pub fn generate(ir: &Ir, sensitive: &super::config::Sensitive) -> Files {
    let mut files = Files::new();
    let always: Vec<&str> = sensitive.always.iter().map(String::as_str).collect();
    let parents: Vec<String> = sensitive
        .number_in_types_containing
        .iter()
        .map(|t| t.to_ascii_lowercase())
        .collect();
    models(ir, &mut files);
    operations(ir, &mut files);
    apis(ir, &mut files);
    files.insert(
        "mod.rs".into(),
        render(quote! {
            //! Code generated from Cybersource's REST spec. See `cargo xtask codegen`.
            #![allow(
                missing_docs,
                clippy::all,
                rustdoc::bare_urls,
                rustdoc::broken_intra_doc_links,
                rustdoc::invalid_html_tags,
                rustdoc::invalid_rust_codeblocks
            )]
            pub mod apis;
            pub mod models;
            pub mod operations;

            /// JSON property names whose values are never logged or printed
            /// (from `spec/codegen.toml [sensitive]`).
            pub(crate) const SENSITIVE_FIELDS: &[&str] = &[#(#always),*];

            /// A `number` property is sensitive when its parent's name
            /// contains one of these (lower case): card, account, ...
            pub(crate) const SENSITIVE_NUMBER_PARENTS: &[&str] = &[#(#parents),*];
        }),
    );
    files
}

/// Pretty-prints tokens as a file with the generated header.
pub fn render(tokens: TokenStream) -> String {
    let file: syn::File = syn::parse2(tokens).expect("generated code must parse");
    format!("{HEADER}{}", prettyplease::unparse(&file))
}

