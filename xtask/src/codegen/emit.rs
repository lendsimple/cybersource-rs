//! Emitting Rust source from the IR.
//!
//! Generated layout (under `src/generated/`):
//! - `models/{shared,<group>}.rs`: models used by several groups (item-level
//!   `cfg(any(...))`) or by one group (module-level `cfg`).
//! - `operations/<group>.rs`: one struct per operation implementing `Operation`.
//! - `apis/<group>.rs`: the `client.<group>()` accessor and `Call` setters.

use std::collections::BTreeMap;

use heck::ToUpperCamelCase;
use proc_macro2::{Ident, Span, TokenStream};
use quote::{format_ident, quote};

use super::ir::{Field, Ir, Mle, Model, Operation, Output, Param, ParamIn, Ty};

/// Names generated models may not take: they would shadow prelude or
/// helper names used by the generated code.
pub const RESERVED_MODEL_NAMES: &[&str] = &[
    "Option", "Some", "None", "Result", "Ok", "Err", "String", "Vec", "Box", "Value", "BTreeMap",
    "Self", "Call", "Bytes", "Cow",
];

/// Methods on `Call` that generated setters must not shadow.
const CALL_METHODS: &[&str] = &[
    "new",
    "op",
    "op_mut",
    "into_op",
    "map_op",
    "send",
    "send_with_response",
    "into_future",
];

const HEADER: &str = "// @generated by `cargo xtask codegen` from spec/cybersource-rest-spec.json.\n// Do not edit by hand; change the generator or spec/codegen.toml instead.\n\n";

/// One generated file: path relative to `src/generated/`, and contents.
pub type Files = BTreeMap<String, String>;

pub fn ident(name: &str) -> Ident {
    match name.strip_prefix("r#") {
        Some(raw) => Ident::new_raw(raw, Span::call_site()),
        None => Ident::new(name, Span::call_site()),
    }
}

/// `#[doc]` attributes, one per line with a leading space, so they print
/// as ordinary `/// text` comments.
fn doc_attrs(doc: Option<&str>) -> TokenStream {
    let lines = doc.into_iter().flat_map(str::lines).map(|l| {
        let l = if l.is_empty() {
            String::new()
        } else {
            format!(" {l}")
        };
        quote! { #[doc = #l] }
    });
    quote! { #(#lines)* }
}

fn doc_line(text: &str) -> TokenStream {
    doc_attrs(Some(text))
}

fn cfg_any(groups: impl IntoIterator<Item = impl AsRef<str>>) -> TokenStream {
    let features: Vec<String> = groups.into_iter().map(|g| g.as_ref().to_owned()).collect();
    match features.as_slice() {
        [one] => quote! { #[cfg(feature = #one)] },
        many => quote! { #[cfg(any(#(feature = #many),*))] },
    }
}

/// The Rust type for a field or element, as used inside `models`.
fn rust_ty(ty: &Ty) -> TokenStream {
    match ty {
        Ty::String => quote! { String },
        Ty::I32 => quote! { i32 },
        Ty::I64 => quote! { i64 },
        Ty::F64 => quote! { f64 },
        Ty::Bool => quote! { bool },
        Ty::Value => quote! { ::serde_json::Value },
        Ty::Vec(t) => {
            let t = rust_ty(t);
            quote! { Vec<#t> }
        }
        Ty::Map(t) => {
            let t = rust_ty(t);
            quote! { ::std::collections::BTreeMap<String, #t> }
        }
        Ty::Model(n) => {
            let n = ident(n);
            quote! { #n }
        }
    }
}

/// The same type referenced from outside the `models` module.
fn qualified_ty(ty: &Ty) -> TokenStream {
    match ty {
        Ty::Vec(t) => {
            let t = qualified_ty(t);
            quote! { Vec<#t> }
        }
        Ty::Map(t) => {
            let t = qualified_ty(t);
            quote! { ::std::collections::BTreeMap<String, #t> }
        }
        Ty::Model(n) => {
            let n = ident(n);
            quote! { crate::models::#n }
        }
        other => rust_ty(other),
    }
}

fn lenient_fn(ty: &Ty) -> Option<&'static str> {
    match ty {
        Ty::String => Some("crate::types::lenient::string"),
        Ty::I32 => Some("crate::types::lenient::i32"),
        Ty::I64 => Some("crate::types::lenient::i64"),
        Ty::F64 => Some("crate::types::lenient::f64"),
        Ty::Bool => Some("crate::types::lenient::bool"),
        _ => None,
    }
}

