fn param_ty(p: &Param) -> TokenStream {
    rust_ty(&p.ty)
}

/// Constructor argument type and conversion for a parameter.
fn param_arg(p: &Param) -> (TokenStream, TokenStream) {
    let name = ident(&p.rust_name);
    match p.ty {
        Ty::String => (quote! { impl Into<String> }, quote! { #name.into() }),
        _ => (param_ty(p), quote! { #name }),
    }
}

fn status_variant(status: u16) -> Ident {
    let name = match status {
        200 => "Ok",
        201 => "Created",
        202 => "Accepted",
        203 => "NonAuthoritative",
        204 => "NoContent",
        206 => "PartialContent",
        other => return format_ident!("Status{}", other),
    };
    format_ident!("{}", name)
}

fn output_ty(op: &Operation) -> (TokenStream, TokenStream, TokenStream) {
    // (type, decode body, extra items)
    match &op.output {
        Output::Unit => (quote! { () }, quote! { Ok(()) }, quote! {}),
        Output::Bytes => (
            quote! { ::bytes::Bytes },
            quote! { Ok(body.clone()) },
            quote! {},
        ),
        Output::Text => (quote! { String }, quote! { text_decode(body) }, quote! {}),
        Output::Json(ty) => (qualified_ty(ty), quote! { json_decode(body) }, quote! {}),
        Output::ByStatus(variants) => {
            let name = format_ident!("{}Response", op.struct_name);
            let defs = variants.iter().map(|(status, ty)| {
                let v = status_variant(*status);
                let doc = doc_line(&format!("HTTP {status}."));
                match ty {
                    Some(ty) => {
                        let ty = qualified_ty(ty);
                        quote! { #doc #v(#ty), }
                    }
                    None => quote! { #doc #v, },
                }
            });
            let arms = variants.iter().map(|(status, ty)| {
                let v = status_variant(*status);
                let status = proc_macro2::Literal::u16_unsuffixed(*status);
                match ty {
                    Some(_) => quote! { #status => Ok(#name::#v(json_decode(body)?)), },
                    None => quote! { #status => Ok(#name::#v), },
                }
            });
            let doc = doc_line(&format!(
                "Response of [`{}`]: the body depends on the HTTP status.",
                op.struct_name
            ));
            (
                quote! { #name },
                quote! {
                    match status.as_u16() {
                        #(#arms)*
                        _ => Err(Error::UnexpectedStatus(status)),
                    }
                },
                quote! {
                    #doc
                    #[derive(Debug, Clone, PartialEq)]
                    #[non_exhaustive]
                    pub enum #name { #(#defs)* }
                },
            )
        }
    }
}

fn mle(m: Mle) -> TokenStream {
    match m {
        Mle::Never => quote! { MlePolicy::Never },
        Mle::Optional => quote! { MlePolicy::Optional },
        Mle::Mandatory => quote! { MlePolicy::Mandatory },
    }
}

fn op_doc(op: &Operation) -> String {
    let what = format!("`{} {}` ({})", op.method, op.path, op.id);
    match &op.doc {
        Some(d) => format!("{d}\n\n{what}"),
        None => what,
    }
}

pub fn operation(op: &Operation) -> TokenStream {
    let name = ident(&op.struct_name);
    let doc = doc_line(&op_doc(op));
    let meta_name = format_ident!(
        "META_{}",
        heck::ToShoutySnakeCase::to_shouty_snake_case(op.struct_name.as_str())
    );
    let method = format_ident!("{}", op.method);
    let (id, path_template) = (&op.id, &op.path);
    let mut meta = quote! { OperationMeta::new(#id, Method::#method, #path_template) };
    if !op.retry_safe {
        meta = quote! { #meta.moves_money() };
    }
    if op.mle_request != Mle::Never || op.mle_response != Mle::Never {
        let (req, resp) = (mle(op.mle_request), mle(op.mle_response));
        meta = quote! { #meta.mle(#req, #resp) };
    }
    if op.no_auth {
        meta = quote! { #meta.no_auth() };
    }
    if op.developer_id {
        meta = quote! { #meta.developer_id() };
    }

    let required: Vec<&Param> = op.params.iter().filter(|p| p.required).collect();
    let optional: Vec<&Param> = op.params.iter().filter(|p| !p.required).collect();

    let fields = op.params.iter().map(|p| {
        let n = ident(&p.rust_name);
        let ty = param_ty(p);
        let doc = doc_attrs(p.doc.as_deref());
        if p.required {
            quote! { #doc pub #n: #ty, }
        } else {
            quote! { #doc pub #n: Option<#ty>, }
        }
    });
    let body_field = op.body.as_ref().map(|t| {
        let t = qualified_ty(t);
        let d = doc_line("The request body.");
        quote! { #d pub body: #t, }
    });

    let args = required.iter().map(|p| {
        let n = ident(&p.rust_name);
        let (ty, _) = param_arg(p);
        quote! { #n: #ty }
    });
    let body_arg = op.body.as_ref().map(|t| {
        let t = qualified_ty(t);
        quote! { body: #t }
    });
    let inits = op.params.iter().map(|p| {
        let n = ident(&p.rust_name);
        if p.required {
            let (_, conv) = param_arg(p);
            quote! { #n: #conv, }
        } else {
            quote! { #n: None, }
        }
    });
    let body_init = op.body.as_ref().map(|_| quote! { body, });
    let all_args: Vec<TokenStream> = args.chain(body_arg).collect();

    let setters = optional.iter().map(|p| {
        let n = ident(&p.rust_name);
        let (ty, conv) = param_arg(p);
        let doc = doc_line(&format!("Sets `{}`.", p.json_name));
        quote! {
            #doc
            pub fn #n(mut self, #n: #ty) -> Self { self.#n = Some(#conv); self }
        }
    });

    // path(): substitute path params, percent-encoded.
    let path_params: Vec<&Param> = op
        .params
        .iter()
        .filter(|p| p.location == ParamIn::Path)
        .collect();
    let path_body = if path_params.is_empty() {
        quote! { Cow::Borrowed(#path_template) }
    } else {
        let mut fmt = op.path.clone();
        let mut values = Vec::new();
        for p in &path_params {
            fmt = fmt.replace(&format!("{{{}}}", p.json_name), "{}");
            let n = ident(&p.rust_name);
            values.push(quote! { encode_path_segment(&self.#n.to_string()) });
        }
        quote! { Cow::Owned(format!(#fmt, #(#values),*)) }
    };

    let query_pushes = op
        .params
        .iter()
        .filter(|p| p.location == ParamIn::Query)
        .map(|p| {
            let n = ident(&p.rust_name);
            let key = &p.json_name;
            if p.required {
                quote! { q.push((#key, self.#n.to_string())); }
            } else {
                quote! { if let Some(v) = &self.#n { q.push((#key, v.to_string())); } }
            }
        });
    let has_query = op.params.iter().any(|p| p.location == ParamIn::Query);
    let query_fn = has_query.then(|| {
        quote! {
            fn query(&self) -> Vec<(&'static str, String)> {
                let mut q = Vec::new();
                #(#query_pushes)*
                q
            }
        }
    });

    let header_inserts = op.params.iter().filter(|p| p.location == ParamIn::Header).map(|p| {
        let n = ident(&p.rust_name);
        let key = p.json_name.to_ascii_lowercase();
        if p.required {
            quote! { insert_header(&mut h, #key, &self.#n.to_string())?; }
        } else {
            quote! { if let Some(v) = &self.#n { insert_header(&mut h, #key, &v.to_string())?; } }
        }
    });
    let has_headers = op.params.iter().any(|p| p.location == ParamIn::Header);
    let headers_fn = has_headers.then(|| {
        quote! {
            fn headers(&self) -> Result<HeaderMap> {
                let mut h = HeaderMap::new();
                #(#header_inserts)*
                Ok(h)
            }
        }
    });

    let body_fn = op.body.as_ref().map(|_| {
        quote! { fn body(&self) -> Result<Option<Bytes>> { json_body(&self.body) } }
    });
    let accept_fn = op.accept.as_ref().map(|a| {
        quote! { fn accept(&self) -> Option<&'static str> { Some(#a) } }
    });

    let (output, decode, extra) = output_ty(op);
    let status_param = if matches!(op.output, Output::ByStatus(_)) {
        quote! { status }
    } else {
        quote! { _status }
    };
    let body_param = if matches!(op.output, Output::Unit) {
        quote! { _body }
    } else {
        quote! { body }
    };
    let new_doc = doc_line(&format!(
        "Creates a `{}` with its required parameters.",
        op.struct_name
    ));

    let paged = op.pagination.as_ref().map(|p| {
        let total = ident(&p.total);
        let items = match &p.count {
            super::ir::PageCount::Field(f) => {
                let f = ident(f);
                quote! { output.#f.and_then(|n| usize::try_from(n).ok()).unwrap_or(0) }
            }
            super::ir::PageCount::Items(f) => {
                let f = ident(f);
                quote! { output.#f.as_ref().map_or(0, Vec::len) }
            }
        };
        let required = |name: &str| op.params.iter().any(|p| p.json_name == name && p.required);
        let (offset, set_offset) = if required("offset") {
            (
                quote! { Some(self.offset) },
                quote! { self.offset = offset; },
            )
        } else {
            (
                quote! { self.offset },
                quote! { self.offset = Some(offset); },
            )
        };
        let limit = if required("limit") {
            quote! { Some(self.limit) }
        } else {
            quote! { self.limit }
        };
        quote! {
            impl crate::flows::pages::Paged for #name {
                fn offset(&self) -> Option<i64> { #offset }
                fn limit(&self) -> Option<i64> { #limit }
                fn set_offset(&mut self, offset: i64) { #set_offset }
                fn page_info(output: &Self::Output) -> crate::flows::pages::PageInfo {
                    crate::flows::pages::PageInfo {
                        items: #items,
                        total: output.#total.map(i64::from),
                    }
                }
            }
        }
    });

    quote! {
        #extra
        #paged

        #doc
        #[derive(Debug, Clone)]
        #[non_exhaustive]
        pub struct #name {
            #(#fields)*
            #body_field
        }

        impl #name {
            #new_doc
            #[allow(clippy::too_many_arguments)]
            pub fn new(#(#all_args),*) -> Self {
                #name { #(#inits)* #body_init }
            }
            #(#setters)*
        }

        static #meta_name: OperationMeta = #meta;

        impl Operation for #name {
            type Output = #output;
            fn meta(&self) -> &'static OperationMeta { &#meta_name }
            fn path(&self) -> Cow<'_, str> { #path_body }
            #query_fn
            #headers_fn
            #body_fn
            #accept_fn
            fn decode(&self, #status_param: StatusCode, #body_param: &Bytes) -> Result<Self::Output> {
                #decode
            }
        }
    }
}

fn operations(ir: &Ir, files: &mut Files) {
    let mut by_group: BTreeMap<&str, Vec<&Operation>> = BTreeMap::new();
    for op in &ir.operations {
        by_group.entry(&op.group).or_default().push(op);
    }
    let mut mod_items = Vec::new();
    for (group, ops) in &by_group {
        let module = format_ident!("{}", group.replace('-', "_"));
        let cfg = cfg_any([group]);
        mod_items.push(quote! {
            #cfg pub mod #module;
            #cfg pub use #module::*;
        });
        let items = ops.iter().map(|op| operation(op));
        files.insert(
            format!("operations/{}.rs", group.replace('-', "_")),
            render(quote! {
                #[allow(unused_imports)]
                use std::borrow::Cow;
                #[allow(unused_imports)]
                use bytes::Bytes;
                #[allow(unused_imports)]
                use http::{HeaderMap, Method, StatusCode};
                #[allow(unused_imports)]
                use crate::operation::{
                    encode_path_segment, insert_header, json_body, json_decode, text_decode,
                    MlePolicy, Operation, OperationMeta,
                };
                #[allow(unused_imports)]
                use crate::{Error, Result};
                #(#items)*
            }),
        );
    }
    files.insert(
        "operations/mod.rs".into(),
        render(quote! {
            //! One struct per API operation, generated from the spec.
            #(#mod_items)*
        }),
    );
}

